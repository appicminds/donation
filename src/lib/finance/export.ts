import writeExcelFile from "write-excel-file/node";
import type { Payment } from "@/payload-types";
import { COLLECTED, minorToDecimal, type DateRange, type FinanceSummary, type FxBasis } from "./report";

/**
 * Accountant exports (PRD §12.3, §13.1). One row per payment, with separate
 * USD and GBP amount columns, settlement figures in the settlement currency,
 * processor references, and the report's range, time and conversion basis.
 */

type Kind = "text" | "money" | "rate" | "date";
type Column = { header: string; kind: Kind; width?: number; get: (p: Payment) => string | number | null | undefined };

const money = (minor: number | null | undefined) => (minor == null ? null : minor);
const iso = (d: string | null | undefined) => (d ? new Date(d).toISOString().replace(".000Z", "Z") : null);

export const COLUMNS: Column[] = [
  { header: "Receipt reference", kind: "text", width: 16, get: (p) => p.receiptRef },
  { header: "Created (UTC)", kind: "date", width: 22, get: (p) => iso(p.createdAt) },
  { header: "Succeeded (UTC)", kind: "date", width: 22, get: (p) => iso(p.succeededAt) },
  { header: "Status", kind: "text", width: 18, get: (p) => p.status },
  { header: "Charge currency", kind: "text", width: 10, get: (p) => p.currency },
  { header: "USD amount", kind: "money", get: (p) => (p.currency === "USD" ? money(p.amountMinor) : null) },
  { header: "GBP amount", kind: "money", get: (p) => (p.currency === "GBP" ? money(p.amountMinor) : null) },
  // Blank unless money was actually collected (pending/failed attempts collected nothing).
  {
    header: "Refunded (charge currency)",
    kind: "money",
    get: (p) => (COLLECTED.has(p.status) ? money(p.refundedMinor ?? 0) : null),
  },
  {
    header: "Amount less refunds (charge currency)",
    kind: "money",
    get: (p) => (COLLECTED.has(p.status) ? money(p.amountMinor - (p.refundedMinor ?? 0)) : null),
  },
  { header: "Settlement currency", kind: "text", width: 10, get: (p) => p.settlementCurrency },
  { header: "Settlement gross", kind: "money", get: (p) => money(p.grossMinor) },
  { header: "Processing fee", kind: "money", get: (p) => money(p.feeMinor) },
  { header: "Net settled (before refunds)", kind: "money", get: (p) => money(p.netMinor) },
  { header: "Stripe FX rate (charge → settlement)", kind: "rate", get: (p) => p.fxRate ?? null },
  { header: "Funds available on (UTC)", kind: "date", width: 22, get: (p) => iso(p.availableOn) },
  { header: "Dispute status", kind: "text", get: (p) => p.disputeStatus },
  { header: "Stripe payment intent", kind: "text", width: 30, get: (p) => p.stripePaymentIntentId },
  { header: "Stripe charge", kind: "text", width: 30, get: (p) => p.stripeChargeId },
  { header: "Stripe balance transaction", kind: "text", width: 30, get: (p) => p.balanceTransactionId },
  { header: "Contributor name", kind: "text", width: 20, get: (p) => p.donorName },
  { header: "Contributor email", kind: "text", width: 28, get: (p) => p.donorEmail },
  { header: "Name may be shown publicly", kind: "text", get: (p) => (p.showName ? "yes" : "no") },
];

export type ExportMeta = { range: DateRange; generatedAt: Date; generatedBy: string; fx: FxBasis | null };

const rangeLabel = (r: DateRange) => `${r.from ?? "beginning"} to ${r.to ?? "today"}`;
const fxLabel = (fx: FxBasis | null) =>
  fx ? `1 GBP = ${fx.gbpToUsd} USD (${fx.source}, ${fx.asOf})` : "No reporting rate set: USD equivalent not calculated";

/** Neutralise spreadsheet formula injection (cells starting with = + - @ or control chars). */
export function safeCell(value: string): string {
  return /^[=+\-@\t\r]/.test(value) ? `'${value}` : value;
}

function csvField(value: string): string {
  const v = safeCell(value);
  return /[",\r\n]/.test(v) ? `"${v.replace(/"/g, '""')}"` : v;
}

function csvValue(col: Column, raw: string | number | null | undefined): string {
  if (raw == null) return "";
  if (col.kind === "money") return minorToDecimal(Number(raw));
  return String(raw);
}

export function toCsv(payments: Payment[], meta: ExportMeta): string {
  const lines: string[][] = [
    ["Comfort Kwaw Memorial Fund: payments export"],
    ["Date range (by creation, UTC)", rangeLabel(meta.range)],
    ["Generated (UTC)", meta.generatedAt.toISOString()],
    ["Generated by", meta.generatedBy],
    ["Reporting FX basis", fxLabel(meta.fx)],
    ["Amounts", "Decimal major units; each amount is in the currency named in its column"],
    [],
    COLUMNS.map((c) => c.header),
    ...payments.map((p) => COLUMNS.map((c) => csvValue(c, c.get(p)))),
  ];
  // UTF-8 BOM so Excel opens names with accents correctly.
  return "﻿" + lines.map((l) => l.map(csvField).join(",")).join("\r\n") + "\r\n";
}

export async function toXlsx(payments: Payment[], summary: FinanceSummary, meta: ExportMeta): Promise<Buffer> {
  const header = COLUMNS.map((c) => ({ value: c.header, fontWeight: "bold" as const }));
  const rows = payments.map((p) =>
    COLUMNS.map((c) => {
      const raw = c.get(p);
      if (raw == null || raw === "") return null;
      if (c.kind === "money") return { value: Number(raw) / 100, type: Number, format: "#,##0.00" };
      if (c.kind === "rate") return { value: Number(raw), type: Number, format: "0.000000" };
      // Typed string cells are never evaluated as formulas in XLSX, so no prefix is needed here.
      return { value: String(raw), type: String };
    }),
  );

  const m = (minor: number) => ({ value: minor / 100, type: Number, format: "#,##0.00" });
  const s = (v: string, bold = false) => ({ value: v, type: String, ...(bold ? { fontWeight: "bold" as const } : {}) });
  const summaryRows = [
    [s("Comfort Kwaw Memorial Fund: finance summary", true)],
    [s("Date range (by creation, UTC)"), s(rangeLabel(meta.range))],
    [s("Generated (UTC)"), s(meta.generatedAt.toISOString())],
    [s("Generated by"), s(meta.generatedBy)],
    [s("Reporting FX basis"), s(fxLabel(meta.fx))],
    [],
    [
      s("By charge currency", true),
      s("Successful", true),
      s("Gross", true),
      s("Refunded", true),
      s("Less refunds", true),
      s("Disputed", true),
    ],
    ...(["USD", "GBP"] as const).map((c) => {
      const t = summary.byCurrency[c];
      return [
        s(c),
        { value: t.successfulCount, type: Number },
        m(t.grossMinor),
        m(t.refundedMinor),
        m(t.netOfRefundsMinor),
        m(t.disputedMinor),
      ];
    }),
    [],
    [
      s("By settlement currency", true),
      s("Payments", true),
      s("Gross settled", true),
      s("Processing fees", true),
      s("Net (before refunds)", true),
    ],
    ...summary.settlement.map((x) => [
      s(x.currency),
      { value: x.count, type: Number },
      m(x.grossMinor),
      m(x.feeMinor),
      m(x.netMinor),
    ]),
    [s("Awaiting settlement figures"), { value: summary.awaitingSettlement, type: Number }],
    [],
    [s("Pending payments"), { value: summary.pendingCount, type: Number }],
    [s("Failed or canceled"), { value: summary.unsuccessfulCount, type: Number }],
    [s("Distinct known supporters"), { value: summary.supporters, type: Number }],
    [
      s("USD equivalent (less refunds)"),
      summary.usdEquivalent ? m(summary.usdEquivalent.totalMinor) : s("Set a reporting rate to calculate"),
    ],
  ];

  const result = writeExcelFile([
    {
      data: summaryRows as never,
      sheet: "Summary",
      columns: [{ width: 34 }, { width: 16 }, { width: 16 }, { width: 16 }, { width: 16 }, { width: 16 }],
    },
    { data: [header, ...rows] as never, sheet: "Payments", columns: COLUMNS.map((c) => ({ width: c.width ?? 16 })) },
  ] as never);
  return await (result as unknown as { toBuffer(): Promise<Buffer> }).toBuffer();
}
